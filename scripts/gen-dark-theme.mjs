// Generates src/styles/dark-theme.css: a dark palette made by remapping Tailwind's colour variables.
// Light tints (50–200) become dark tints and dark text shades (700–950) become light, so every existing
// utility class (bg-emerald-50, text-slate-900, border-slate-200 …) adapts without per-page dark: classes.
// Run after upgrading Tailwind: node scripts/gen-dark-theme.mjs
import fs from 'node:fs';

const theme = fs.readFileSync(new URL('../node_modules/tailwindcss/theme.css', import.meta.url), 'utf8');
const vars = {};
for (const m of theme.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) (vars[m[1]] ??= {})[m[2]] = m[3].trim();
// our brand scale (index.css @theme) — keep in sync
vars.brand = { 50: '#eef2ff', 100: '#e0e7ff', 500: '#6366f1', 600: '#4f46e5', 700: '#4338ca', 300: '#a5b4fc', 400: '#818cf8', 200: '#c7d2fe', 800: '#3730a3', 900: '#312e81', 950: '#1e1b4b' };

const NEUTRAL = ['slate', 'gray', 'zinc', 'neutral', 'stone'];
const CHROMA_MAP = { 50: '950', 100: '900', 200: '800', 700: '300', 800: '200', 900: '100', 950: '50' };
// neutrals carry most text and surfaces, so they get a full, contrast-tuned inversion
const NEUTRAL_MAP = { 50: '950', 100: '800', 200: '700', 300: '600', 400: '500', 500: '400', 600: '300', 700: '200', 800: '100', 900: '50', 950: '50' };

const lines = [];
const restore = [];
for (const [name, scale] of Object.entries(vars)) {
  const map = NEUTRAL.includes(name) ? NEUTRAL_MAP : CHROMA_MAP;
  for (const [shade, target] of Object.entries(map)) {
    if (!scale[shade] || !scale[target]) continue;
    // tints on dark backgrounds read better slightly translucent
    const value = !NEUTRAL.includes(name) && Number(shade) <= 100 ? `color-mix(in oklab, ${scale[target]} 70%, transparent)` : scale[target];
    lines.push(`  --color-${name}-${shade}: ${value};`);
    restore.push(`  --color-${name}-${shade}: ${scale[shade]};`);
  }
}

const css = `/* Generated by scripts/gen-dark-theme.mjs — do not edit by hand. */
html.dark {
  color-scheme: dark;
${lines.join('\n')}
}

/* Surfaces: white is also used for text on buttons, so only backgrounds/borders are remapped. */
html.dark .bg-white { background-color: #0f172a; }
html.dark [class~='bg-white/90'] { background-color: rgb(15 23 42 / 0.9); }
html.dark .border-white { border-color: #0f172a; }
html.dark body { background-color: #020617; }

/* Elements that are meant to be dark in both themes (camera boxes, code blocks, overlays). */
html.dark .bg-slate-900 { background-color: #0b1120; }
html.dark [class~='bg-slate-900/40'] { background-color: rgb(0 0 0 / 0.6); }

/* Opt-out: anything inside .dark-keep keeps the light palette (e.g. the branded login panel). */
html.dark .dark-keep {
${restore.join('\n')}
}

html.dark input, html.dark select, html.dark textarea { color-scheme: dark; }
html.dark ::placeholder { color: #64748b; }
`;
fs.mkdirSync(new URL('../src/styles/', import.meta.url), { recursive: true });
fs.writeFileSync(new URL('../src/styles/dark-theme.css', import.meta.url), css);
console.log(`dark-theme.css: ${lines.length} variables remapped`);
